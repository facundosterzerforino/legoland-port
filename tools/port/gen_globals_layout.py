"""tools/port/gen_globals_layout.py: port/port_globals_layout.c, a table of the game's globals (src/legoland/globals.c,
in the original's address order): their original address, their address and size in this build. -port-selftest
checks with it that the globals the original has next to each other are next to each other here too:
the decompiled code walks from one into the next in places (the map screen's markers, the string table's slots), and
a linker that orders them otherwise makes those walks go through other globals."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, 'src/legoland/globals.c')).read().splitlines()
header = open(os.path.join(ROOT, 'src/legoland/globals.h')).read()
entries = []
i = 0
while i < len(src):
    m = re.match(r'// GLOBAL: LEGOLAND (0x[0-9a-fA-F]+)', src[i])
    if not m:
        i += 1
        continue
    addr = int(m.group(1), 16)
    j = i + 1
    while j < len(src) and (src[j].strip().startswith('//') or not src[j].strip()):
        j += 1
    if j >= len(src):
        break
    line = src[j].split('=')[0]
    fp = re.search(r'\(\s*\*\s*([A-Za-z_]\w*)', line)
    if fp:
        name = fp.group(1)
    else:
        m2 = re.search(r'([A-Za-z_]\w*)\s*(\[[^\]]*\]\s*)*;?\s*$', line.strip().rstrip(';').rstrip())
        name = m2.group(1) if m2 else None
    if name and re.search(r'\b%s\b' % re.escape(name), header) and name not in ('const', 'struct'):
        entries.append((addr, name))
    i = j + 1
entries.sort()
out = ['/* GENERATED by tools/port/gen_globals_layout.py from src/legoland/globals.c: the game\'s globals in the',
       ' * original\'s address order, for -port-selftest (port_data.c). Do not edit. */',
       '#include <windows.h>', '#include <mmsystem.h>', '#include <ddraw.h>', '#include <dinput.h>', '#include <dsound.h>',
       '#include "../src/legoland/legoland.h"', '#include "../src/legoland/globals.h"'] + ['#include "../src/legoland/%s"' % h for h in sorted(os.listdir(os.path.join(ROOT, 'src/legoland'))) if h.endswith('.h') and h not in ('legoland.h', 'globals.h')] + ['#include "port_globals_layout.h"',
       '', 'const struct PortLayoutGlobal PortLayoutGlobals[] = {']
for addr, name in entries:
    if re.search(r'extern[^;]*\b%s\s*\[\s*\]' % re.escape(name), header):
        out.append('    {0x%08x, "%s", (const void *)&%s, 0}, /* no size in globals.h */' % (addr, name, name))
    else:
        out.append('    {0x%08x, "%s", (const void *)&%s, sizeof(%s)},' % (addr, name, name, name))
out += ['};', '', 'const int PortLayoutGlobalCount = sizeof(PortLayoutGlobals) / sizeof(PortLayoutGlobals[0]);', '']
open(os.path.join(ROOT, 'port/port_globals_layout.c'), 'w').write('\n'.join(out))
open(os.path.join(ROOT, 'port/port_globals_layout.h'), 'w').write('''#ifndef PORT_GLOBALS_LAYOUT_H
#define PORT_GLOBALS_LAYOUT_H

#include <stddef.h>

/* the game's globals in the original's address order (port_globals_layout.c, generated) */
struct PortLayoutGlobal {
    unsigned int original; /* its address in legoland.exe */
    const char *name;
    const void *address; /* here */
    size_t size; /* here */
};

extern const struct PortLayoutGlobal PortLayoutGlobals[];
extern const int PortLayoutGlobalCount;

#endif
''')
print('globals:', len(entries))
