#!/usr/bin/env python3
"""Generate port/port_x86.c and port/port_x86.h: converters between the original 32-bit struct layout and the port's.

The game's data files hold some structs exactly as the original program had them in memory (an object class's
fixed part is a struct Ride), and so do its saved games (the rides' nodes, the work orders, ...). A 64-bit build
lays those structs out differently (pointers are 8 bytes), so it can't read or write them in place. For each type
listed in TYPES, tools/port_layout.py gives the original layout; this writes a field table (original offset,
offsetof in the port, size, kind), PortFromX86() and PortToX86(), which copy the fields between an original-layout
buffer and the port's struct, a descriptor per type and PORT_X86_TYPE(p), which picks the descriptor of the type p
points to (NULL for any other type). Pointer fields keep the file's 32-bit value (zero-extended): the code that
reads them later fixes them up or overwrites them, as it did on 32-bit; written out, they keep their low 32 bits.

Usage: python3 tools/gen_x86.py   (run from the repo root; rerun after the listed types change)
"""
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# struct Ride: the object classes' files. The others: what the saved games hold (tools/phase8/audit_save.py checks
# that every SaveGameRead/SaveGameWrite of a struct whose layout differs on 64 bits is listed here).
TYPES = ["struct Ride",
        "struct BNVPath", "struct BalloonNode", "struct BarrelNode", "struct BlokeSave", "struct BoatRide",
        "struct BoatRideNode", "struct BrollyNode", "struct BuildObj", "struct CarouselNode", "struct CatapultNode",
        "struct CopterNode", "struct CountNode", "struct EarthNode", "struct EditState", "struct FlumeEntry",
        "struct FlumeNode", "struct Footprint", "struct GoldNode", "struct JailCell", "struct JoustNode",
        "struct JungleFish", "struct JungleObj", "struct JunglePath", "struct JungleRide", "struct JungleScore",
        "struct MapElement", "struct MermaidNode", "struct NewBloke", "struct ObjectiveEvent", "struct PathNode",
        "struct PlaneRideNode", "struct PumpNode", "struct RideQueueEntry", "struct SafariNode", "struct SaveBlock",
        "struct SlideNode", "struct SpaceTowerCar", "struct SpiderNode", "struct WaterNode", "struct WorkOrder",
        "struct WorkerSave"]


def flatten(t, desig, off):
    k = t["k"]
    if k == "B":
        return [(off, desig, t["n"], "B")] if t["n"] else []
    if k in ("P", "Q"):
        return [(off, desig, 4, k)]
    if k == "R":
        out = []
        for d, sub in t["f"]:
            out += flatten(sub, desig + d, off + sub["o"])
        return out
    if k == "A":
        out = []
        for i in range(t["n"]):
            out += flatten(t["e"], "%s[%d]" % (desig, i), off + i * t["s"])
        return out
    raise ValueError(k)


def ident(t):
    return re.sub(r"\W", "_", t.replace("struct ", "").replace("union ", "")).strip("_")


def main():
    tf = tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False)
    tf.write("\n".join(TYPES))
    tf.close()
    try:
        r = subprocess.run(["uv", "run", "-q", "--no-project", "--with", "libclang==18.1.1", "python",
                            str(ROOT / "tools/port_layout.py"), "--types", tf.name], capture_output=True, text=True,
                           check=True)
    finally:
        os.unlink(tf.name)
    lay = json.loads(r.stdout)
    if lay["errors"]:
        print("port_layout.py: %d parse errors, first: %s" % (len(lay["errors"]), lay["errors"][0]), file=sys.stderr)
        sys.exit(1)
    missing = [t for t in TYPES if t not in lay["globals"]]
    if missing:
        print("not laid out (not in a header?): %s" % ", ".join(missing), file=sys.stderr)
        sys.exit(1)
    h = ["/* GENERATED by tools/gen_x86.py -- do not edit. */\n",
         "/* [port] Converters between the original 32-bit layout of the structs the game files and the saved games\n"
         "   hold and the port's (tools/gen_x86.py). */\n",
         "#ifndef PORT_X86_H\n#define PORT_X86_H\n\n",
         "struct PortX86Field {\n    unsigned short src;  /* offset in the original layout */\n"
         "    unsigned short dst;  /* offsetof in the port */\n    unsigned short size; /* bytes ('B'), 4 for 'P'/'Q' */\n"
         "    unsigned char kind;  /* 'B' bytes, 'P' pointer, 'Q' pointer-sized integer */\n};\n\n",
         "/* A converted type: its fields, its size in the original and in the port. */\n"
         "struct PortX86Type {\n    const struct PortX86Field *fields;\n    unsigned int count;\n"
         "    unsigned int size_x86;\n    unsigned int size;\n    const char *name;\n};\n\n",
         "/* Copies the fields of src, the bytes [from, to) of a struct in its original layout, into the port's struct\n"
         "   dst; pointer fields get the original 32-bit value, zero-extended. Fields outside [from, to) are left. */\n"
         "void PortFromX86(void *dst, const unsigned char *src, const struct PortX86Field *fields, unsigned int count,\n"
         "                 unsigned int from, unsigned int to);\n\n",
         "/* Writes the port's struct src in the original layout to dst (size_x86 bytes): pointer fields as their low\n"
         "   32 bits, the bytes no field covers (padding) as zeros. */\n"
         "void PortToX86(unsigned char *dst, const void *src, const struct PortX86Type *type);\n\n",
         "/* every converted type, for the self-test */\nextern const struct PortX86Type *const port_x86_types[];\n"
         "extern const unsigned int port_x86_type_count;\n\n"]
    c = ["/* GENERATED by tools/gen_x86.py -- do not edit. */\n",
         "#include <stddef.h>\n#include <string.h>\n#include <windows.h>\n"]
    for hh in sorted((ROOT / "src/legoland").glob("*.h")):
        c.append('#include "../src/legoland/%s"\n' % hh.name)
    c.append('#include "port_x86.h"\n\n')
    generic = []
    for t in TYPES:
        g = lay["globals"][t]
        n = ident(t)
        leaves = flatten(g["t"], "", 0)
        h.append("/* %s: %d fields, 0x%x bytes in the original */\n" % (t, len(leaves), g["size"]))
        h.append("#define PORT_X86_SIZE_%s 0x%xu\n" % (n, g["size"]))
        if t == "struct Ride":
            tops = {}
            for off, d, size, kind in leaves:
                m = re.match(r"\.(\w+)", d)
                if m and m.group(1) not in tops:
                    tops[m.group(1)] = off
            for name, off in tops.items():
                h.append("#define PORT_X86_OFF_%s_%s 0x%xu\n" % (n, name, off))
        h.append("%s;\nextern const struct PortX86Field port_x86_%s[];\nextern const unsigned int port_x86_%s_count;\n"
                 "extern const struct PortX86Type port_x86_type_%s;\n\n" % (t, n, n, n))
        c.append("const struct PortX86Field port_x86_%s[] = {\n" % n)
        for off, d, size, kind in leaves:
            dst = "offsetof(%s, %s)" % (t, d.lstrip(".")) if d else "0"
            c.append("    {0x%x, %s, %d, '%s'},\n" % (off, dst, size, kind))
        c.append("};\nconst unsigned int port_x86_%s_count = sizeof(port_x86_%s) / sizeof(port_x86_%s[0]);\n" % (n, n, n))
        c.append("const struct PortX86Type port_x86_type_%s = {port_x86_%s, sizeof(port_x86_%s) / sizeof(port_x86_%s[0]), "
                 "0x%x, sizeof(%s), \"%s\"};\n\n" % (n, n, n, n, g["size"], t, t))
        generic.append("%s *: &port_x86_type_%s, const %s *: &port_x86_type_%s" % (t, n, t, n))
    h.append("/* The descriptor of the type p points to (an array decays to its first element), NULL for any other. */\n"
             "#define PORT_X86_TYPE(p) \\\n    _Generic((p), \\\n")
    for gline in generic:
        h.append("        %s, \\\n" % gline)
    h.append("        default: (const struct PortX86Type *)0)\n\n#endif\n")
    c.append("const struct PortX86Type *const port_x86_types[] = {\n")
    for t in TYPES:
        c.append("    &port_x86_type_%s,\n" % ident(t))
    c.append("};\nconst unsigned int port_x86_type_count = sizeof(port_x86_types) / sizeof(port_x86_types[0]);\n\n")
    c.append(r"""void PortFromX86(void *dst, const unsigned char *src, const struct PortX86Field *fields, unsigned int count,
                 unsigned int from, unsigned int to) {
    unsigned int i;

    for (i = 0; i < count; i++) {
        const struct PortX86Field *f = &fields[i];
        unsigned int a = f->src;
        unsigned int b = f->src + f->size;

        if (b <= from || a >= to) {
            continue;
        }
        if (f->kind == 'B') {
            /* a byte run partly inside [from, to): its covered part */
            unsigned int lo = a < from ? from : a;
            unsigned int hi = b > to ? to : b;
            memcpy((char *)dst + f->dst + (lo - a), src + (lo - from), hi - lo);
        } else if (a >= from && b <= to) {
            unsigned int v;
            UINT_PTR p;

            memcpy(&v, src + (a - from), 4);
            p = v;
            memcpy((char *)dst + f->dst, &p, sizeof(p));
        }
    }
}

void PortToX86(unsigned char *dst, const void *src, const struct PortX86Type *type) {
    unsigned int i;

    memset(dst, 0, type->size_x86);
    for (i = 0; i < type->count; i++) {
        const struct PortX86Field *f = &type->fields[i];

        if (f->kind == 'B') {
            memcpy(dst + f->src, (const char *)src + f->dst, f->size);
        } else {
            UINT_PTR p;
            unsigned int v;

            memcpy(&p, (const char *)src + f->dst, sizeof(p));
            v = (unsigned int)p;
            memcpy(dst + f->src, &v, 4);
        }
    }
}
""")
    (ROOT / "port/port_x86.h").write_text("".join(h), encoding="latin-1")
    (ROOT / "port/port_x86.c").write_text("".join(c), encoding="latin-1")
    print("wrote port/port_x86.c, port/port_x86.h (%d types)" % len(TYPES))


if __name__ == "__main__":
    main()
