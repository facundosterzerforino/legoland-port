#!/usr/bin/env python3
"""Generate port/port_x86.c and port/port_x86.h: converters from the game files' 32-bit struct layout.

The game's data files hold some structs exactly as the original program had them in memory (an object class's
fixed part is a struct Ride). A 64-bit build lays those structs out differently (pointers are 8 bytes), so it
can't read them in place. For each type listed in TYPES, tools/port_layout.py gives the original layout; this
writes a field table (original offset, offsetof in the port, size, kind) and PortFromX86(), which copies the
fields of an original-layout buffer into the port's struct. Pointer fields keep the file's 32-bit value
(zero-extended): the code that reads them later fixes them up or overwrites them, as it did on 32-bit.

Usage: python3 tools/gen_x86.py   (run from the repo root; rerun after the listed types change)
"""
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = ["struct Ride"]


def flatten(t, desig, off):
    k = t["k"]
    if k == "B":
        return [(off, desig, t["n"], "B")] if t["n"] else []
    if k in ("P", "Q"):
        return [(off, desig, 4, k)]
    if k == "R":
        out = []
        for d, sub in t["f"]:
            out += flatten(sub, desig + d, off + sub["o"])
        return out
    if k == "A":
        out = []
        for i in range(t["n"]):
            out += flatten(t["e"], "%s[%d]" % (desig, i), off + i * t["s"])
        return out
    raise ValueError(k)


def ident(t):
    return re.sub(r"\W", "_", t.replace("struct ", "").replace("union ", "")).strip("_")


def main():
    tf = tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False)
    tf.write("\n".join(TYPES))
    tf.close()
    try:
        r = subprocess.run(["uv", "run", "-q", "--no-project", "--with", "libclang==18.1.1", "python",
                            str(ROOT / "tools/port_layout.py"), "--types", tf.name], capture_output=True, text=True,
                           check=True)
    finally:
        os.unlink(tf.name)
    lay = json.loads(r.stdout)
    if lay["errors"]:
        print("port_layout.py: %d parse errors, first: %s" % (len(lay["errors"]), lay["errors"][0]), file=sys.stderr)
        sys.exit(1)
    h = ["/* GENERATED by tools/gen_x86.py -- do not edit. */\n",
         "/* [port] Converters from the original 32-bit layout of the structs the game files hold (tools/gen_x86.py). */\n",
         "#ifndef PORT_X86_H\n#define PORT_X86_H\n\n",
         "struct PortX86Field {\n    unsigned short src;  /* offset in the original layout */\n"
         "    unsigned short dst;  /* offsetof in the port */\n    unsigned short size; /* bytes ('B'), 4 for 'P'/'Q' */\n"
         "    unsigned char kind;  /* 'B' bytes, 'P' pointer, 'Q' pointer-sized integer */\n};\n\n",
         "/* Copies the fields of src, the bytes [from, to) of a struct in its original layout, into the port's struct\n"
         "   dst; pointer fields get the original 32-bit value, zero-extended. Fields outside [from, to) are left. */\n"
         "void PortFromX86(void *dst, const unsigned char *src, const struct PortX86Field *fields, unsigned int count,\n"
         "                 unsigned int from, unsigned int to);\n\n"]
    c = ["/* GENERATED by tools/gen_x86.py -- do not edit. */\n",
         "#include <stddef.h>\n#include <string.h>\n#include <windows.h>\n"]
    for hh in sorted((ROOT / "src/legoland").glob("*.h")):
        c.append('#include "../src/legoland/%s"\n' % hh.name)
    c.append('#include "port_x86.h"\n\n')
    for t in TYPES:
        g = lay["globals"][t]
        n = ident(t)
        leaves = flatten(g["t"], "", 0)
        h.append("/* %s: %d fields, 0x%x bytes in the original */\n" % (t, len(leaves), g["size"]))
        h.append("#define PORT_X86_SIZE_%s 0x%xu\n" % (n, g["size"]))
        tops = {}
        for off, d, size, kind in leaves:
            m = re.match(r"\.(\w+)", d)
            if m and m.group(1) not in tops:
                tops[m.group(1)] = off
        for name, off in tops.items():
            h.append("#define PORT_X86_OFF_%s_%s 0x%xu\n" % (n, name, off))
        h.append("extern const struct PortX86Field port_x86_%s[];\nextern const unsigned int port_x86_%s_count;\n\n" % (n, n))
        c.append("const struct PortX86Field port_x86_%s[] = {\n" % n)
        for off, d, size, kind in leaves:
            dst = "offsetof(%s, %s)" % (t, d.lstrip(".")) if d else "0"
            c.append("    {0x%x, %s, %d, '%s'},\n" % (off, dst, size, kind))
        c.append("};\nconst unsigned int port_x86_%s_count = sizeof(port_x86_%s) / sizeof(port_x86_%s[0]);\n\n" % (n, n, n))
    h.append("#endif\n")
    c.append(r"""void PortFromX86(void *dst, const unsigned char *src, const struct PortX86Field *fields, unsigned int count,
                 unsigned int from, unsigned int to) {
    unsigned int i;

    for (i = 0; i < count; i++) {
        const struct PortX86Field *f = &fields[i];
        unsigned int a = f->src;
        unsigned int b = f->src + f->size;

        if (b <= from || a >= to) {
            continue;
        }
        if (f->kind == 'B') {
            /* a byte run partly inside [from, to): its covered part */
            unsigned int lo = a < from ? from : a;
            unsigned int hi = b > to ? to : b;
            memcpy((char *)dst + f->dst + (lo - a), src + (lo - from), hi - lo);
        } else if (a >= from && b <= to) {
            unsigned int v;
            UINT_PTR p;

            memcpy(&v, src + (a - from), 4);
            p = v;
            memcpy((char *)dst + f->dst, &p, sizeof(p));
        }
    }
}
""")
    (ROOT / "port/port_x86.h").write_text("".join(h), encoding="latin-1")
    (ROOT / "port/port_x86.c").write_text("".join(c), encoding="latin-1")
    print("wrote port/port_x86.c, port/port_x86.h (%s)" % ", ".join(TYPES))


if __name__ == "__main__":
    main()
